def parse_script():
    raw = open(os.path.join(SRC, "script_original.txt"), encoding="utf-8").read()
    raw = unicodedata.normalize("NFC", raw)
    lines = [l.strip() for l in raw.splitlines()]
    title = lines[0]
    chapters = []
    head = re.compile(r"^(\d)\.〈(.+?)〉——(.+)$")
    for l in lines[1:]:
        if not l:
            continue
        m = head.match(l)
        if m:
            chapters.append({"n": int(m.group(1)), "song": m.group(2), "form_raw": m.group(3), "paras": []})
        else:
            chapters[-1]["paras"].append(l)
    return title, chapters


