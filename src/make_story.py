    pages.append({"id": "end", "kind": "end", "title": title, "credits": CREDITS, "scene": "end", "alt": ALT["end"],
                  "art": ART["end"], "heigou": heigou_look("end")})
    story = {"title": title, "credits_raw": CREDITS_RAW, "form_changes": FORM_SHOW, "pages": pages}
    out = os.path.join(SRC, "story.json")
